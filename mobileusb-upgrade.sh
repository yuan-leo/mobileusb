#!/bin/bash
# MobileUSB upgrade: self-contained source installer. No network-fetched scripts.
set -Eeuo pipefail
TEMP=$(mktemp -d)
trap 'rm -rf -- "$TEMP"' EXIT
awk 'seen { print } /^__MOBILEUSB_PAYLOAD__$/ { seen=1 }' "$0" | base64 -d > "$TEMP/payload.tar.gz"
printf '%s  %s\n' 'fcc0ba61190e4885f020cd2926b7f521816754595c0cd1a789efe10879d00875' "$TEMP/payload.tar.gz" | sha256sum --check --status
tar -xzf "$TEMP/payload.tar.gz" -C "$TEMP"
if [ "${1:-}" = '--extract' ]; then
    DEST=${2:?Supply a destination directory}
    mkdir -p -- "$DEST"
    cp -a "$TEMP/src" "$TEMP/tests" "$TEMP/install.sh" "$TEMP/restore.py" "$TEMP/README.md" "$TEMP/test-results.log" "$DEST/"
    printf 'Source extracted to %s\n' "$DEST"
    exit 0
fi
bash "$TEMP/install.sh" "$@"
exit 0
